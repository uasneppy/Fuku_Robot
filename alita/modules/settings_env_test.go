// edits returns the editMessageText calls on message msgID of chatID, in order.
func (e *settingsEnv) edits(chatID, msgID int64) []moduleBotCall {
	var matched []moduleBotCall
	for _, call := range callsToChat(e.fake.staffBotClient, "editMessageText", chatID) {
		if staffParamInt(call.Params, "message_id") == msgID {
			matched = append(matched, call)
		}
	}
	return matched
}

// lastEdit is the text and keyboard of the last edit of message msgID of chatID. An edit
// without reply_markup has a nil keyboard. It fails the test when the message was never
// edited.
func (e *settingsEnv) lastEdit(chatID, msgID int64) (string, [][]gotgbot.InlineKeyboardButton) {
	e.t.Helper()
	edits := e.edits(chatID, msgID)
	if len(edits) == 0 {
		e.t.Fatalf("message %d of chat %d was never edited", msgID, chatID)
	}
	last := edits[len(edits)-1]
	return fmt.Sprint(last.Params["text"]), staffKeyboardOf(last.Params["reply_markup"])
}

// answerCount counts the answerCallbackQuery calls so far.
func (e *settingsEnv) answerCount() int {
	return len(e.fake.callsFor("answerCallbackQuery"))
}

// groupFields is the field set of a button of a menu opened in the group: the opener u
// plus the given key, value pairs.
func (e *settingsEnv) groupFields(opener gotgbot.User, kv ...string) map[string]string {
	fields := map[string]string{"u": fmt.Sprint(opener.Id)}
	for i := 0; i+1 < len(kv); i += 2 {
		fields[kv[i]] = kv[i+1]
	}
	return fields
}

// privateFields is the field set of a button of a menu opened in private: the group's
// chat ID c plus the given key, value pairs.
func (e *settingsEnv) privateFields(groupID int64, kv ...string) map[string]string {
	fields := map[string]string{"c": fmt.Sprint(groupID)}
	for i := 0; i+1 < len(kv); i += 2 {
		fields[kv[i]] = kv[i+1]
	}
	return fields
}

// memberLookupsOf counts the getChatMember calls about userID in chatID.
func (e *settingsEnv) memberLookupsOf(chatID, userID int64) int {
	count := 0
	for _, call := range callsToChat(e.fake.staffBotClient, "getChatMember", chatID) {
		if staffParamInt(call.Params, "user_id") == userID {
			count++
		}
	}
	return count
}

// settingsAllButtons flattens a keyboard into its buttons, row by row.
func settingsAllButtons(keyboard [][]gotgbot.InlineKeyboardButton) []gotgbot.InlineKeyboardButton {
	var all []gotgbot.InlineKeyboardButton
	for _, row := range keyboard {
		all = append(all, row...)
	}
	return all
}

// settingsButtonByMarker returns the first button whose label carries the marker of the
// locale key.
func settingsButtonByMarker(keyboard [][]gotgbot.InlineKeyboardButton, key string) (gotgbot.InlineKeyboardButton, bool) {
	for _, button := range settingsAllButtons(keyboard) {
		if containsMarker(button.Text, key) {
			return button, true
		}
	}
	return gotgbot.InlineKeyboardButton{}, false
}

// containsMarker reports whether text carries the marker of the locale key.
func containsMarker(text, key string) bool {
	return strings.Contains(text, staffMarker(key))
}

// settingsButtonFields decodes a settings button's callback data into its fields,
// failing the test on data of another namespace.
func settingsButtonFields(t *testing.T, button gotgbot.InlineKeyboardButton) map[string]string {
	t.Helper()
	decoded, ok := decodeCallbackData(button.CallbackData, settingsCallbackNamespace)
	if !ok {
		t.Fatalf("button %q carries %q, not settings callback data", button.Text, button.CallbackData)
	}
	return decoded.Fields
}
