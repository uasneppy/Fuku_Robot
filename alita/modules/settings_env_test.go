// settingsEnv is the shared toolkit of the settings menu tests: a lockdown environment
// (one supergroup, one administrator with can_restrict_members, a hand-written Bot API
// fake, miniredis) with the Settings, Captcha, Antiflood, Staff and Help modules and the
// anonymous-admin proof loaded on its dispatcher. Page plans call these helpers by name
// and do not edit this file, so they take any chat, any user and raw fields.
type settingsEnv struct {
	*lockdownEnv
}

// settingsEnvOptions chooses how the environment is built.
type settingsEnvOptions struct {
	// RealLocale keeps the real locale files instead of the marker locale, for a test
	// that reads the real words of a language.
	RealLocale bool
}

// newSettingsEnv builds the environment with the marker locale.
func newSettingsEnv(t *testing.T) *settingsEnv {
	t.Helper()
	return newSettingsEnvWith(t, settingsEnvOptions{})
}

// newSettingsEnvWith builds the environment exactly as newLockdownEnv does and then loads
// the modules a menu page reaches. With RealLocale it skips the marker locale.
func newSettingsEnvWith(t *testing.T, opts settingsEnvOptions) *settingsEnv {
	t.Helper()
	var base *lockdownEnv
	if !opts.RealLocale {
		base = newLockdownEnv(t)
	} else {
		base = newRealLocaleLockdownEnv(t)
	}
	env := &settingsEnv{lockdownEnv: base}

	// The administrator is also in the admin list the cached command checks read.
	env.fake.setCreator(env.chat.Id, env.admin.Id)

	LoadSettings(env.dispatcher)
	LoadCaptcha(env.dispatcher)
	LoadAntiflood(env.dispatcher)
	LoadStaff(env.dispatcher)
	LoadHelp(env.dispatcher)
	LoadBotUpdates(env.dispatcher)

	settingsCleanup(t, env.chat.Id)
	return env
}

// newRealLocaleLockdownEnv is newLockdownEnv without the marker locale.
func newRealLocaleLockdownEnv(t *testing.T) *lockdownEnv {
	t.Helper()
	redisServer := withMiniredisServer(t)
	withFastLockdownPacer(t)

	fake := newLockdownFake()
	bot := newModuleTestBot(fake.moduleBotClient)
	bot.BotClient = fake

	env := &lockdownEnv{
		t:          t,
		redis:      redisServer,
		fake:       fake,
		bot:        bot,
		chat:       gotgbot.Chat{Id: uniqueModuleChatID(), Type: "supergroup", Title: "Lock Chat"},
		admin:      gotgbot.User{Id: uniqueLinkOwnerID(), FirstName: "Ad<b>min"},
		nextUpdate: 100,
	}
	lockdownCleanup(t, env.chat.Id)

	fake.setMember(env.chat.Id, env.admin.Id, staffFakeMember{
		Status:             gotgbot.ChatMemberStatusAdministrator,
		CanRestrictMembers: true,
	})
	fake.setChatPermsRaw(env.chat.Id, lockdownTestPrePermissions)

	env.dispatcher = ext.NewDispatcher(&ext.DispatcherOpts{MaxRoutines: -1})
	LoadLockdown(env.dispatcher)
	t.Cleanup(raidPosts.wait)
	return env
}

// settingsCleanup removes the settings rows of the given chats, and their cached copies,
// before and after the test.
func settingsCleanup(t *testing.T, chatIDs ...int64) {
	t.Helper()
	clean := func() {
		if len(chatIDs) == 0 {
			return
		}
		db.DB.Where("chat_id IN ?", chatIDs).Delete(&models.CaptchaSettings{})
		db.DB.Where("chat_id IN ?", chatIDs).Delete(&models.AntifloodSettings{})
		db.DB.Where("chat_id IN ?", chatIDs).Delete(&models.Chat{})
		for _, id := range chatIDs {
			dbcache.DeleteCache(dbcache.CacheKey("captcha_settings", id))
			dbcache.DeleteCache(dbcache.CacheKey("antiflood", id))
			dbcache.DeleteCache(dbcache.CacheKey("chat_lang", id))
			dbcache.DeleteCache(dbcache.CacheKey("chat_settings", id))
			dbcache.DeleteCache(dbcache.CacheKey("chat", id))
		}
		dbcache.ResetLocalForTest()
	}
	clean()
	t.Cleanup(clean)
	raidCleanup(t, chatIDs...)
	lockdownCleanup(t, chatIDs...)
}

// addChat adds a second supergroup, as lockdownEnv.addChat does, and cleans its settings
// rows up as well. The administrator is also in its admin list.
func (e *settingsEnv) addChat() gotgbot.Chat {
	e.t.Helper()
	chat := e.lockdownEnv.addChat()
	e.fake.setCreator(chat.Id, e.admin.Id)
	settingsCleanup(e.t, chat.Id)
	return chat
}

// sendIn runs a text message in chat as from through the real dispatcher and returns the
// message's ID.
func (e *settingsEnv) sendIn(chat gotgbot.Chat, from gotgbot.User, text string) int64 {
	e.t.Helper()
	id := e.updateID()
	update := &gotgbot.Update{
		UpdateId: id,
		Message: &gotgbot.Message{
			MessageId: id,
			Date:      1,
			Chat:      chat,
			From:      &from,
			Text:      text,
		},
	}
	if err := e.dispatcher.ProcessUpdate(e.bot, update, nil); err != nil {
		e.t.Fatalf("ProcessUpdate(%d) error = %v", id, err)
	}
	return id
}

// sendPrivate runs a text message in from's private chat with the bot.
func (e *settingsEnv) sendPrivate(from gotgbot.User, text string) {
	e.t.Helper()
	e.sendIn(gotgbot.Chat{Id: from.Id, Type: "private", FirstName: from.FirstName}, from, text)
}

// newestChoice returns the message ID and the Open here button of the newest choice
// message the bot sent to the env's chat, failing the test when there is none.
func (e *settingsEnv) newestChoice() (int64, gotgbot.InlineKeyboardButton) {
	e.t.Helper()
	sent := e.fake.sentTo(e.chat.Id)
	for i := len(sent) - 1; i >= 0; i-- {
		keyboard := staffKeyboardOf(sent[i].Params["reply_markup"])
		for _, button := range settingsAllButtons(keyboard) {
			decoded, ok := decodeCallbackData(button.CallbackData, settingsCallbackNamespace)
			if ok && decoded.Fields["a"] == settingsActOpenHere {
				return sent[i].MessageID, button
			}
		}
	}
	e.t.Fatal("the bot sent no settings choice message to the chat")
	return 0, gotgbot.InlineKeyboardButton{}
}

// openMenu sends /settings as opener, presses Open here of the choice message as opener
// and returns the ID of the message, which is then the Main page.
func (e *settingsEnv) openMenu(opener gotgbot.User) int64 {
	e.t.Helper()
	e.send(opener, "/settings")
	msgID, button := e.newestChoice()
	e.pressRaw(e.chat, opener, msgID, button.CallbackData)
	return msgID
}

// press presses a button of the message msgID of the env's chat. The data is encoded
// from fields, and the test fails when it does not encode.
func (e *settingsEnv) press(from gotgbot.User, msgID int64, fields map[string]string) {
	e.t.Helper()
	data := encodeCallbackData(settingsCallbackNamespace, fields)
	if data == "" {
		e.t.Fatalf("settings callback data %v did not encode", fields)
	}
	e.pressRaw(e.chat, from, msgID, data)
}

// pressRaw presses a button carrying data, on message msgID of any chat, as any user.
func (e *settingsEnv) pressRaw(chat gotgbot.Chat, from gotgbot.User, msgID int64, data string) {
	e.t.Helper()
	id := e.updateID()
	update := &gotgbot.Update{
		UpdateId: id,
		CallbackQuery: &gotgbot.CallbackQuery{
			Id:           fmt.Sprintf("settings-%d", id),
			From:         from,
			Message:      gotgbot.Message{MessageId: msgID, Date: 1, Chat: chat},
			Data:         data,
			ChatInstance: "settings-test",
		},
	}
	if err := e.dispatcher.ProcessUpdate(e.bot, update, nil); err != nil {
		e.t.Fatalf("ProcessUpdate(%d) error = %v", id, err)
	}
}

