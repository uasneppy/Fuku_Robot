// memberReqEnv is the shared toolkit of every member requirements test: the settings
// environment (one supergroup with an administrator, a hand-written Bot API fake with
// per-user profiles, miniredis) plus the requirement pacer made fast and the cleanup of
// everything a requirement test writes. Later Phase 13 plans call these helpers by name and
// do not edit this file.
//
// Hygiene (CI runs all of fuku/modules in one PostgreSQL database in source order): members
// are minted with uniqueLinkOwnerID, chats are the settings environment's own unique chats,
// and assertions read hold rows by chat and user, never by table count.
type memberReqEnv struct {
	*settingsEnv
}

// withFastMemberReqPacer installs a requirement pacer with a 1 ms interval and a 5 ms
// retry_after unit for the test, so a 429 costs milliseconds and the production pacer's
// 100 ms spacing does not slow the suite.
func withFastMemberReqPacer(t *testing.T) {
	t.Helper()
	previous := memberReqPacer
	memberReqPacer = ratelimit.NewTelegramPacer(ratelimit.TelegramPacerOptions{
		NextKey:        "fuku:memberreq:pace:next",
		BlockKey:       "fuku:memberreq:pace:block",
		Interval:       time.Millisecond,
		MaxRetries:     3,
		MaxWait:        60 * time.Second,
		RetryAfterUnit: 5 * time.Millisecond,
	})
	t.Cleanup(func() { memberReqPacer = previous })
}

// newMemberReqEnv builds the environment with the marker locale.
func newMemberReqEnv(t *testing.T) *memberReqEnv {
	t.Helper()
	return newMemberReqEnvWith(t, settingsEnvOptions{})
}

// newMemberReqEnvWith builds the environment; RealLocale keeps the real locale files, for a
// test that reads the words of a language.
func newMemberReqEnvWith(t *testing.T, opts settingsEnvOptions) *memberReqEnv {
	t.Helper()
	env := &memberReqEnv{settingsEnv: newSettingsEnvWith(t, opts)}
	withFastMemberReqPacer(t)
	memberReqCleanup(t, []int64{env.chat.Id}, nil)
	return env
}

// memberReqCleanup deletes, before the test and again when it ends, what a requirement test
// writes for the given chats (requirement settings and holds, warns and warn settings,
// approvals, captcha attempts, their cache keys and the fuku:memberreq:* keys in Redis) and
// for the given members (the users rows warns.WarnUser creates and their cache keys), then
// empties the in-process cache layer. Either list may be empty.
func memberReqCleanup(t *testing.T, chatIDs, userIDs []int64) {
	t.Helper()
	clean := func() {
		if len(chatIDs) > 0 {
			db.DB.Where("chat_id IN ?", chatIDs).Delete(&models.ChatRequirements{})
			db.DB.Where("chat_id IN ?", chatIDs).Delete(&models.ChatRequirementHold{})
			db.DB.Where("chat_id IN ?", chatIDs).Delete(&models.Warns{})
			db.DB.Where("chat_id IN ?", chatIDs).Delete(&models.WarnSettings{})
			db.DB.Where("chat_id IN ?", chatIDs).Delete(&models.ApprovedUsers{})
			db.DB.Where("chat_id IN ?", chatIDs).Delete(&models.CaptchaAttempts{})
			for _, id := range chatIDs {
				dbcache.DeleteCache(dbcache.CacheKey("member_requirements", id))
				dbcache.DeleteCache(dbcache.CacheKey("approvals", id))
				dbcache.DeleteCache(dbcache.CacheKey("captcha_pending", id))
				dbcache.DeleteCache(dbcache.CacheKey("warn_settings", id))
			}
			memberReqDeleteRedisKeys(chatIDs)
		}
		if len(userIDs) > 0 {
			db.DB.Where("user_id IN ?", userIDs).Delete(&models.User{})
			for _, id := range userIDs {
				dbcache.DeleteCache(dbcache.CacheKey("user", id))
			}
		}
		dbcache.ResetLocalForTest()
	}
	clean()
	t.Cleanup(clean)
}

// memberReqDeleteRedisKeys removes the fuku:memberreq:* keys that name one of chatIDs.
func memberReqDeleteRedisKeys(chatIDs []int64) {
	_, _, client := cache.GetCacheState()
	if client == nil {
		return
	}
	ctx := context.Background()
	keys, err := client.Keys(ctx, "fuku:memberreq:*").Result()
	if err != nil {
		return
	}
	for _, key := range keys {
		for _, id := range chatIDs {
			if strings.Contains(key, fmt.Sprint(id)) {
				client.Del(ctx, key)
				break
			}
		}
	}
}

// mreqMember mints a member of the environment's group with the given names: a fresh user
// ID, a profile the fake reports in every getChatMember answer and a plain member record.
// Its users row and cache key are deleted when the test ends.
func (e *memberReqEnv) mreqMember(first, last, username string) gotgbot.User {
	e.t.Helper()
	id := uniqueLinkOwnerID()
	memberReqCleanup(e.t, nil, []int64{id})
	e.fake.setProfile(id, first, last, username)
	e.fake.setMember(e.chat.Id, id, staffFakeMember{
		Status:          gotgbot.ChatMemberStatusMember,
		IsMember:        true,
		CanSendMessages: true,
	})
	return gotgbot.User{Id: id, FirstName: first, LastName: last, Username: username}
}

// mreqRules stores the punishment of each named rule for the group through the real
// repository and returns the stored settings, as the executor's caller reads them.
func (e *memberReqEnv) mreqRules(actions map[memberreq.Rule]int) *models.ChatRequirements {
	e.t.Helper()
	ctx := context.Background()
	for rule, action := range actions {
		if err := memberreq.SetRuleAction(ctx, e.chat.Id, rule, action); err != nil {
			e.t.Fatalf("SetRuleAction(%s, %d) error = %v", rule, action, err)
		}
	}
	row, err := memberreq.GetSettingsFresh(ctx, e.chat.Id)
	if err != nil {
		e.t.Fatalf("GetSettingsFresh error = %v", err)
	}
	return row
}

// mreqCase is the executor's input for a message of user in the group, with the group's
// stored settings read fresh.
func (e *memberReqEnv) mreqCase(user gotgbot.User) memberReqCase {
	e.t.Helper()
	row, err := memberreq.GetSettingsFresh(context.Background(), e.chat.Id)
	if err != nil {
		e.t.Fatalf("GetSettingsFresh error = %v", err)
	}
	return memberReqCase{
		Chat:        e.chat,
		User:        user,
		Source:      memberReqFromMessage,
		MessageID:   e.updateID(),
		MessageDate: time.Now().Unix(),
		Settings:    row,
	}
}

// mreqEnforce runs the executor for c with the environment's bot.
func (e *memberReqEnv) mreqEnforce(c memberReqCase) memberReqResult {
	e.t.Helper()
	return memberReqEnforce(context.Background(), e.bot, c)
}

// mreqHold reads the member's hold in the group fresh, or nil when there is none.
func (e *memberReqEnv) mreqHold(userID int64) *models.ChatRequirementHold {
	e.t.Helper()
	hold, err := memberreq.GetHoldFresh(context.Background(), e.chat.Id, userID)
	if err != nil {
		e.t.Fatalf("GetHoldFresh(%d) error = %v", userID, err)
	}
	return hold
}

// mreqNotices returns the messages the bot sent to the group, in order.
func (e *memberReqEnv) mreqNotices() []staffSentMessage {
	e.t.Helper()
	return e.fake.sentTo(e.chat.Id)
}

// mreqWrites returns the ban, restrict and unban calls addressed to the group.
func (e *memberReqEnv) mreqWrites() []moduleBotCall {
	e.t.Helper()
	var all []moduleBotCall
	for _, method := range []string{"banChatMember", "restrictChatMember", "unbanChatMember"} {
		all = append(all, e.calls(method)...)
	}
	return all
}

// mreqWarnRow reads the member's warns row in the group, or nil when there is none.
func (e *memberReqEnv) mreqWarnRow(userID int64) *models.Warns {
	e.t.Helper()
	var rows []models.Warns
	if err := db.DB.Where("chat_id = ? AND user_id = ?", e.chat.Id, userID).Find(&rows).Error; err != nil {
		e.t.Fatalf("read warns of %d: %v", userID, err)
	}
	if len(rows) == 0 {
		return nil
	}
	return &rows[0]
}
